// Builds one self-contained IIFE per chain from src/inpage/entries, then writes
// src/script/bundles.generated.ts embedding each bundle as a string so
// buildInjectedScript() needs no file system at runtime.
//
// Self-contained matters: a WebView has no bundler, and Firefox/Safari register
// these through scripting.registerContentScripts, which takes one file per entry
// and will not follow a dynamic import.
import { build } from "vite";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entriesDir = resolve(root, "src/inpage/entries");
const outDir = resolve(root, "dist/inpage");
const generated = resolve(root, "src/script/bundles.generated.ts");

async function entries() {
  const files = await readdir(entriesDir);
  return files
    .filter((f) => f.endsWith(".ts") && f !== "bootstrap.ts")
    .map((f) => ({ name: f.slice(0, -3), entry: resolve(entriesDir, f) }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

async function newestSourceTime() {
  let newest = 0;
  const walk = async (dir) => {
    for (const item of await readdir(dir, { withFileTypes: true })) {
      const path = resolve(dir, item.name);
      if (item.isDirectory()) await walk(path);
      else newest = Math.max(newest, (await stat(path)).mtimeMs);
    }
  };
  for (const dir of ["src/inpage", "src/protocol", "src/transports"]) {
    await walk(resolve(root, dir));
  }
  newest = Math.max(newest, (await stat(resolve(root, "scripts/bundle-inpage.mjs"))).mtimeMs);
  return newest;
}

async function isFresh() {
  try {
    const [out, newest] = await Promise.all([stat(generated), newestSourceTime()]);
    return out.mtimeMs > newest;
  } catch {
    return false;
  }
}

if (!process.argv.includes("--force") && (await isFresh())) {
  process.exit(0);
}

const list = await entries();
const bundles = {};

for (const { name, entry } of list) {
  await build({
    root,
    configFile: false,
    logLevel: "error",
    publicDir: false,
    build: {
      lib: { entry, name: `inpageWallet_${name.replace(/-/g, "_")}`, formats: ["iife"], fileName: () => `${name}.iife.js` },
      outDir,
      emptyOutDir: false,
      target: "es2017",
      minify: "esbuild",
      sourcemap: false,
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  });
  bundles[name] = await readFile(resolve(outDir, `${name}.iife.js`), "utf8");
}

await mkdir(dirname(generated), { recursive: true });
await writeFile(
  generated,
  `// Generated by scripts/bundle-inpage.mjs. Do not edit.\n` +
    `export const INPAGE_BUNDLES: Record<string, string> = ${JSON.stringify(bundles, null, 2)};\n`,
  "utf8",
);

console.log(`bundled ${list.length} inpage entr${list.length === 1 ? "y" : "ies"}`);
