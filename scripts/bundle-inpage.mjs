// Builds one self-contained IIFE per chain from src/inpage/entries, then writes
// src/script/bundles.generated.ts embedding each bundle as a string so
// buildInjectedScript() needs no file system at runtime.
//
// Self-contained matters: a WebView has no bundler, and Firefox/Safari register
// these through scripting.registerContentScripts, which takes one file per entry
// and will not follow a dynamic import.
import { build } from "vite";
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entriesDir = resolve(root, "src/inpage/entries");
const outDir = resolve(root, "dist/inpage");
const generated = resolve(root, "src/script/bundles.generated.ts");
const HASH_MARKER = "// source-hash: ";

async function entries() {
  const files = await readdir(entriesDir);
  return files
    .filter((f) => f.endsWith(".ts") && f !== "bootstrap.ts")
    .map((f) => ({ name: f.slice(0, -3), entry: resolve(entriesDir, f) }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

// Content, not mtimes: a checkout, a rebase or a touched file all move an mtime
// without changing what the bundle would contain, and a restored older file
// changes the content without moving it forward.
async function sourceHash() {
  const files = [];
  const walk = async (dir) => {
    for (const item of await readdir(dir, { withFileTypes: true })) {
      const path = resolve(dir, item.name);
      if (item.isDirectory()) await walk(path);
      else files.push(path);
    }
  };
  for (const dir of ["src/inpage", "src/protocol", "src/transports"]) {
    await walk(resolve(root, dir));
  }
  files.push(resolve(root, "scripts/bundle-inpage.mjs"));

  const hash = createHash("sha256");
  for (const path of files.sort()) {
    hash.update(relative(root, path).split("\\").join("/"));
    hash.update("\0");
    hash.update(await readFile(path));
    hash.update("\0");
  }
  return hash.digest("hex");
}

async function generatedHash() {
  try {
    const head = (await readFile(generated, "utf8")).slice(0, 512);
    const line = head.split("\n").find((l) => l.startsWith(HASH_MARKER));
    return line ? line.slice(HASH_MARKER.length).trim() : null;
  } catch {
    return null;
  }
}

const hash = await sourceHash();
if (!process.argv.includes("--force") && (await generatedHash()) === hash) {
  process.exit(0);
}

const list = await entries();
const bundles = {};

for (const [index, { name, entry }] of list.entries()) {
  await build({
    root,
    configFile: false,
    logLevel: "error",
    publicDir: false,
    build: {
      lib: { entry, name: `inpageWallet_${name.replace(/-/g, "_")}`, formats: ["iife"], fileName: () => `${name}.iife.js` },
      outDir,
      // Cleared once, then appended to: every entry shares the directory, and a
      // stale bundle from a deleted entry must not survive into size-limit.
      emptyOutDir: index === 0,
      target: "es2017",
      minify: "esbuild",
      sourcemap: false,
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  });
  // Rollup's IIFE wrapper is not the outermost scope of what it writes: esbuild
  // lowers the object spread to the es2017 target after rollup has wrapped, and
  // hoists its helpers above that wrapper as top-level `var`s. Two bundles
  // evaluated in one document then overwrite each other's helpers, and the
  // loser posts envelopes built by the winner's copy. Wrapping the whole file
  // is what makes it self-contained.
  const file = resolve(outDir, `${name}.iife.js`);
  const code = `(function(){\n${(await readFile(file, "utf8")).trim()}\n})();\n`;
  await writeFile(file, code, "utf8");
  bundles[name] = code;
}

await mkdir(dirname(generated), { recursive: true });
await writeFile(
  generated,
  `// Generated by scripts/bundle-inpage.mjs. Do not edit.\n` +
    `${HASH_MARKER}${hash}\n` +
    `export const INPAGE_BUNDLES: Record<string, string> = ${JSON.stringify(bundles, null, 2)};\n`,
  "utf8",
);

console.log(`bundled ${list.length} inpage entr${list.length === 1 ? "y" : "ies"}`);
